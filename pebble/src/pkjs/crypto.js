/* Pure-JS crypto for the Wafflelist Pebble app.
 *
 * PebbleKit JS has no WebCrypto, so this module reimplements exactly the
 * primitives the Wafflelist web client uses (src/lib/crypto.ts):
 *   - PBKDF2-SHA256 (user id derivation, 600k iterations)
 *   - HKDF-SHA256 (encryption key + signing seed derivation)
 *   - AES-256-GCM (todo blob encryption)
 *   - Ed25519 (request signing; RFC 8032, matches WebCrypto)
 *
 * Everything here is verified byte-for-byte against Node's WebCrypto by
 * test/crypto.test.cjs. ES5 only - this runs inside the Pebble mobile
 * app's JS sandbox.
 *
 * The Ed25519 implementation is derived from TweetNaCl.js (public domain).
 * SHA constant tables are generated by tools/gen-sha-constants.mjs.
 */

