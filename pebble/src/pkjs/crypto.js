var sha256W = new Int32Array(64);

// Processes len bytes (multiple of 64) starting at data[off] into state[8].
function sha256Blocks(state, data, off, len) {
  var w = sha256W;
  var end = off + len;
  for (var p = off; p < end; p += 64) {
    var i, x, y;
    for (i = 0; i < 16; i++) {
      w[i] = (data[p + 4 * i] << 24) | (data[p + 4 * i + 1] << 16) | (data[p + 4 * i + 2] << 8) | data[p + 4 * i + 3];
    }
    for (i = 16; i < 64; i++) {
      x = w[i - 15];
      y = w[i - 2];
      w[i] = (w[i - 16]
        + (((x >>> 7) | (x << 25)) ^ ((x >>> 18) | (x << 14)) ^ (x >>> 3))
        + w[i - 7]
        + (((y >>> 17) | (y << 15)) ^ ((y >>> 19) | (y << 13)) ^ (y >>> 10))) | 0;
    }
    var a = state[0], b = state[1], c = state[2], d = state[3];
    var e = state[4], f = state[5], g = state[6], h = state[7];
    for (i = 0; i < 64; i++) {
      var t1 = (h
        + (((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7)))
        + ((e & f) ^ (~e & g))
        + SHA256_K[i] + w[i]) | 0;
      var t2 = ((((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10)))
        + ((a & b) ^ (a & c) ^ (b & c))) | 0;
      h = g; g = f; f = e; e = (d + t1) | 0;
      d = c; c = b; b = a; a = (t1 + t2) | 0;
    }
    state[0] = (state[0] + a) | 0;
    state[1] = (state[1] + b) | 0;
    state[2] = (state[2] + c) | 0;
    state[3] = (state[3] + d) | 0;
    state[4] = (state[4] + e) | 0;
    state[5] = (state[5] + f) | 0;
    state[6] = (state[6] + g) | 0;
    state[7] = (state[7] + h) | 0;
  }
}

function sha256StateToBytes(state, out) {
  for (var i = 0; i < 8; i++) {
    out[4 * i] = (state[i] >>> 24) & 0xff;
    out[4 * i + 1] = (state[i] >>> 16) & 0xff;
    out[4 * i + 2] = (state[i] >>> 8) & 0xff;
    out[4 * i + 3] = state[i] & 0xff;
  }
  return out;
}

function sha256(msg) {
  var state = new Int32Array(SHA256_H0);
  var len = msg.length;
  var full = len - (len % 64);
  sha256Blocks(state, msg, 0, full);
  var rem = len - full;
  var tail = new Uint8Array(rem + 9 > 64 ? 128 : 64);
  for (var i = 0; i < rem; i++) tail[i] = msg[full + i];
  tail[rem] = 0x80;
  var tl = tail.length;
  var bitsHi = Math.floor(len / 0x20000000);
  var bitsLo = (len * 8) >>> 0;
  tail[tl - 8] = (bitsHi >>> 24) & 0xff;
  tail[tl - 7] = (bitsHi >>> 16) & 0xff;
  tail[tl - 6] = (bitsHi >>> 8) & 0xff;
  tail[tl - 5] = bitsHi & 0xff;
  tail[tl - 4] = (bitsLo >>> 24) & 0xff;
  tail[tl - 3] = (bitsLo >>> 16) & 0xff;
  tail[tl - 2] = (bitsLo >>> 8) & 0xff;
  tail[tl - 1] = bitsLo & 0xff;
  sha256Blocks(state, tail, 0, tl);
  return sha256StateToBytes(state, new Uint8Array(32));
}

/* ---------------- HMAC-SHA256 ---------------- */

function hmacSha256Init(key) {
  if (key.length > 64) key = sha256(key);
  var ipad = new Uint8Array(64);
  var opad = new Uint8Array(64);
  for (var i = 0; i < 64; i++) {
    var k = i < key.length ? key[i] : 0;
    ipad[i] = k ^ 0x36;
    opad[i] = k ^ 0x5c;
  }
  var iState = new Int32Array(SHA256_H0);
  sha256Blocks(iState, ipad, 0, 64);
  var oState = new Int32Array(SHA256_H0);
  sha256Blocks(oState, opad, 0, 64);
  return { iState: iState, oState: oState };
}

// Generic HMAC for arbitrary-length messages.
function hmacSha256(key, msg) {
  var ctx = hmacSha256Init(key);

  var state = new Int32Array(ctx.iState);
  var len = msg.length;
  var full = len - (len % 64);
  sha256Blocks(state, msg, 0, full);
  var rem = len - full;
  var tail = new Uint8Array(rem + 9 > 64 ? 128 : 64);
  for (var i = 0; i < rem; i++) tail[i] = msg[full + i];
  tail[rem] = 0x80;
  var total = 64 + len; // ipad block + message
  var tl = tail.length;
  var bitsHi = Math.floor(total / 0x20000000);
  var bitsLo = (total * 8) >>> 0;
  tail[tl - 8] = (bitsHi >>> 24) & 0xff;
  tail[tl - 7] = (bitsHi >>> 16) & 0xff;
  tail[tl - 6] = (bitsHi >>> 8) & 0xff;
  tail[tl - 5] = bitsHi & 0xff;
  tail[tl - 4] = (bitsLo >>> 24) & 0xff;
  tail[tl - 3] = (bitsLo >>> 16) & 0xff;
  tail[tl - 2] = (bitsLo >>> 8) & 0xff;
  tail[tl - 1] = bitsLo & 0xff;
  sha256Blocks(state, tail, 0, tl);
  var inner = sha256StateToBytes(state, new Uint8Array(32));

  return hmacFinishOuter(ctx.oState, inner);
}

// outer = SHA256(opad-state, digest32). One padded block.
var hmacOuterBlock = new Uint8Array(64);

function hmacFinishOuter(oState, digest32) {
  var blk = hmacOuterBlock;
  for (var i = 0; i < 32; i++) blk[i] = digest32[i];
  blk[32] = 0x80;
  for (i = 33; i < 62; i++) blk[i] = 0;
  blk[62] = 0x03; // (64 + 32) * 8 = 768 bits
  blk[63] = 0x00;
  var state = new Int32Array(oState);
  sha256Blocks(state, blk, 0, 64);
  return sha256StateToBytes(state, new Uint8Array(32));
}

/* ---------------- PBKDF2-SHA256 (single 32-byte block) ---------------- */

// Runs `count` iterations of the PBKDF2 inner loop using precomputed HMAC
// midstates: 2 SHA-256 compressions per iteration.
function pbkdf2Round(ctx, u, t, count) {
  var innerBlk = new Uint8Array(64);
  innerBlk[32] = 0x80;
  innerBlk[62] = 0x03; // 768-bit total length, same shape as hmacFinishOuter
  var outerBlk = new Uint8Array(64);
  outerBlk[32] = 0x80;
  outerBlk[62] = 0x03;
  var state = new Int32Array(8);
  var i, j;
  for (i = 0; i < count; i++) {
    for (j = 0; j < 32; j++) innerBlk[j] = u[j];
    state.set(ctx.iState);
    sha256Blocks(state, innerBlk, 0, 64);
    sha256StateToBytes(state, u);
    for (j = 0; j < 32; j++) outerBlk[j] = u[j];
    state.set(ctx.oState);
    sha256Blocks(state, outerBlk, 0, 64);
    sha256StateToBytes(state, u);
    for (j = 0; j < 32; j++) t[j] ^= u[j];
  }
}

function pbkdf2Sha256(password, salt, iterations) {
  var ctx = hmacSha256Init(password);
  var u = hmacSha256(password, concatBytes(salt, new Uint8Array([0, 0, 0, 1])));
  var t = new Uint8Array(u);
  pbkdf2Round(ctx, u, t, iterations - 1);
  return t;
}

// Chunked variant so the (multi-second) 600k-iteration derivation doesn't
// block the PebbleKit JS thread in one go. cb(result), progress(done, total).
function pbkdf2Sha256Async(password, salt, iterations, cb, progress) {
  var ctx = hmacSha256Init(password);
  var u = hmacSha256(password, concatBytes(salt, new Uint8Array([0, 0, 0, 1])));
  var t = new Uint8Array(u);
  var remaining = iterations - 1;
  var done = 1;
  var CHUNK = 25000;

  function step() {
    var n = remaining < CHUNK ? remaining : CHUNK;
    pbkdf2Round(ctx, u, t, n);
    remaining -= n;
    done += n;
    if (progress) progress(done, iterations);
    if (remaining > 0) {
      setTimeout(step, 0);
    } else {
      cb(t);
    }
  }
  setTimeout(step, 0);
}

/* ---------------- HKDF-SHA256 (32-byte output) ---------------- */

function hkdfSha256(ikm, salt, info) {
  var prk = hmacSha256(salt, ikm);
  return hmacSha256(prk, concatBytes(info, new Uint8Array([1])));
}

