/* ---------------- byte helpers ---------------- */

function utf8Encode(str) {
  var out = [];
  for (var i = 0; i < str.length; i++) {
    var c = str.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff && i + 1 < str.length) {
      var lo = str.charCodeAt(i + 1);
      if (lo >= 0xdc00 && lo <= 0xdfff) {
        c = 0x10000 + ((c - 0xd800) << 10) + (lo - 0xdc00);
        i++;
      }
    }
    if (c < 0x80) {
      out.push(c);
    } else if (c < 0x800) {
      out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    } else if (c < 0x10000) {
      out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    } else {
      out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    }
  }
  return new Uint8Array(out);
}

function utf8Decode(bytes) {
  var out = '';
  var i = 0;
  while (i < bytes.length) {
    var b = bytes[i];
    var c;
    if (b < 0x80) {
      c = b; i += 1;
    } else if ((b & 0xe0) === 0xc0) {
      c = ((b & 31) << 6) | (bytes[i + 1] & 63); i += 2;
    } else if ((b & 0xf0) === 0xe0) {
      c = ((b & 15) << 12) | ((bytes[i + 1] & 63) << 6) | (bytes[i + 2] & 63); i += 3;
    } else {
      c = ((b & 7) << 18) | ((bytes[i + 1] & 63) << 12) | ((bytes[i + 2] & 63) << 6) | (bytes[i + 3] & 63); i += 4;
    }
    if (c >= 0x10000) {
      c -= 0x10000;
      out += String.fromCharCode(0xd800 + (c >> 10), 0xdc00 + (c & 0x3ff));
    } else {
      out += String.fromCharCode(c);
    }
  }
  return out;
}

var HEX = '0123456789abcdef';

function bytesToHex(bytes) {
  var out = '';
  for (var i = 0; i < bytes.length; i++) {
    out += HEX[bytes[i] >> 4] + HEX[bytes[i] & 15];
  }
  return out;
}

function hexToBytes(hex) {
  var out = new Uint8Array(hex.length / 2);
  for (var i = 0; i < out.length; i++) {
    out[i] = parseInt(hex.substr(i * 2, 2), 16);
  }
  return out;
}

var B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

function bytesToBase64(bytes) {
  var out = '';
  var i;
  for (i = 0; i + 2 < bytes.length; i += 3) {
    var n = (bytes[i] << 16) | (bytes[i + 1] << 8) | bytes[i + 2];
    out += B64[(n >> 18) & 63] + B64[(n >> 12) & 63] + B64[(n >> 6) & 63] + B64[n & 63];
  }
  var rem = bytes.length - i;
  if (rem === 1) {
    out += B64[bytes[i] >> 2] + B64[(bytes[i] << 4) & 63] + '==';
  } else if (rem === 2) {
    out += B64[bytes[i] >> 2] + B64[((bytes[i] << 4) | (bytes[i + 1] >> 4)) & 63] + B64[(bytes[i + 1] << 2) & 63] + '=';
  }
  return out;
}

var B64_REV = (function () {
  var rev = {};
  for (var i = 0; i < 64; i++) rev[B64[i]] = i;
  return rev;
})();

function base64ToBytes(str) {
  str = str.replace(/[\s=]+$/, '').replace(/\s+/g, '');
  var len = Math.floor(str.length * 3 / 4);
  var out = new Uint8Array(len);
  var o = 0;
  for (var i = 0; i + 3 < str.length; i += 4) {
    var n = (B64_REV[str[i]] << 18) | (B64_REV[str[i + 1]] << 12) | (B64_REV[str[i + 2]] << 6) | B64_REV[str[i + 3]];
    out[o++] = (n >> 16) & 0xff;
    out[o++] = (n >> 8) & 0xff;
    out[o++] = n & 0xff;
  }
  var rem = str.length - i;
  if (rem === 2) {
    out[o++] = (B64_REV[str[i]] << 2) | (B64_REV[str[i + 1]] >> 4);
  } else if (rem === 3) {
    var m = (B64_REV[str[i]] << 10) | (B64_REV[str[i + 1]] << 4) | (B64_REV[str[i + 2]] >> 2);
    out[o++] = (m >> 8) & 0xff;
    out[o++] = m & 0xff;
  }
  return out;
}

function concatBytes() {
  var total = 0, i;
  for (i = 0; i < arguments.length; i++) total += arguments[i].length;
  var out = new Uint8Array(total);
  var off = 0;
  for (i = 0; i < arguments.length; i++) {
    out.set(arguments[i], off);
    off += arguments[i].length;
  }
  return out;
}

